/** 把 ANIM/ 之后的短名翻成中文，未收录时回退原名 */
export function localizeAnimationName(short: string): string {
  const override = FULL_LABELS[short]
  if (override) return override

  const [head, ...rest] = short.split(/[-_]/)
  const headLabel = GROUP_LABELS[head]
  if (!headLabel) return short

  const parts = rest.map((part) => PART_LABELS[part] ?? part)
  return [headLabel, ...parts].join(' ')
}

/** 分组标题：一条动作直接显示动作名，多条用前缀译名 */
export function localizeAnimationGroup(token: string, items: string[]): string {
  if (items.length === 1) return localizeAnimationName(items[0])
  return GROUP_LABELS[token] ?? token
}
